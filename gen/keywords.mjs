// Writes spec/clingo/keywords.json, the `#` directives and the word keywords of the
// vendored tree-sitter grammar, and the directive list the completion source offers.
import {writeFileSync} from "node:fs"
import {walk, writeJson} from "./grammar.mjs"

const directives = new Set(), words = new Set()
walk(node => {
  if (node.type != "STRING") return
  if (/^#[a-z]+\+?$/.test(node.value)) directives.add(node.value)
  if (/^[a-z]+$/.test(node.value)) words.add(node.value)
})

const keywords = {directives: [...directives].sort(), words: [...words].sort()}
writeFileSync(...writeJson("../spec/clingo/keywords.json", keywords))
writeFileSync(
  new URL("../packages/codemirror-lang-asp/src/keywords.ts", import.meta.url),
  "// Generated by gen/keywords.mjs from spec/clingo/keywords.json. Do not edit.\n\n" +
    `export const directives = ${JSON.stringify(keywords.directives)}\n`,
)
